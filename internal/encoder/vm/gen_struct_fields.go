// keyedIntSpec describes an integer scalar opcode whose padded key and formatted
// digits are emitted together via a single AppendPaddedKey helper.
type keyedIntSpec struct {
	Op       string
	GoType   string
	AppendFn string
	CastExpr string
}

// floatScalarSpec describes a floating-point scalar opcode with IEEE-754 signed-zero
// omitempty semantics and NaN/Inf error or null handling.
type floatScalarSpec struct {
	Op           string
	GoType       string
	ZeroBitsExpr string
	CastF64Expr  string
	FormatFn     string
}

// typedSliceSpec describes a typed slice opcode ([]T) with shared nil/empty/omitempty
// key handling and element body formatting.
type typedSliceSpec struct {
	Op       string
	GoType   string
	Kind     string // "eface", "i64", "str", "helper", "fallible"
	HelperFn string
}

type loopVariant struct {
	Name        string
	Dense       bool
	Sanitized   bool
	SanitizeArg string
	KeyedInts   []keyedIntSpec
	Floats      []floatScalarSpec
	Slices      []typedSliceSpec
}

