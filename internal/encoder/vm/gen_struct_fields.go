func render() ([]byte, error) {
	variants := []loopVariant{
		{
			Name:        "encodeStructFieldsDense",
			Dense:       true,
			Sanitized:   false,
			SanitizeArg: "0",
			KeyedInts:   authoritativeKeyedInts,
			Floats:      authoritativeFloats,
			Slices:      authoritativeSlices,
		},
		{
			Name:        "encodeStructFieldsSanitizedDense",
			Dense:       true,
			Sanitized:   true,
			SanitizeArg: "sanitize",
			KeyedInts:   authoritativeKeyedInts,
			Floats:      authoritativeFloats,
			Slices:      authoritativeSlices,
		},
		{
			Name:        "encodeStructFieldsDefault",
			Dense:       false,
			Sanitized:   false,
			SanitizeArg: "0",
			KeyedInts:   authoritativeKeyedInts,
			Floats:      authoritativeFloats,
			Slices:      authoritativeSlices,
		},
		{
			Name:        "encodeStructFieldsSanitized",
			Dense:       false,
			Sanitized:   true,
			SanitizeArg: "sanitize",
			KeyedInts:   authoritativeKeyedInts,
			Floats:      authoritativeFloats,
			Slices:      authoritativeSlices,
		},
	}

	tmpl, err := template.New("struct_fields").Parse(structFieldsTmpl)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, variants); err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}

func main() {
	check := flag.Bool("check", false, "verify struct_fields_gen.go matches generated output")
	flag.Parse()

	src, err := render()
	if err != nil {
		panic(err)
	}
	const outPath = "struct_fields_gen.go"
	if *check {
		got, err := os.ReadFile(outPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "read %s: %v\n", outPath, err)
			os.Exit(1)
		}
		if !bytes.Equal(got, src) {
			fmt.Fprintf(os.Stderr, "%s is out of sync with gen_struct_fields.go; run `go generate ./internal/encoder/vm`\n", outPath)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(outPath, src, 0644); err != nil {
		panic(err)
	}
}
